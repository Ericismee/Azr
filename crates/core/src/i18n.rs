pub fn is_known(src: &str) -> bool {
    VI.iter().any(|(k, _)| *k == src)
}
pub fn tr(lang: Lang, src: &'static str) -> &'static str {
    match lang {
        Lang::En => src,
        Lang::Vi => VI
            .iter()
            .find(|(k, _)| *k == src)
            .map(|(_, v)| *v)
            .unwrap_or(src),
    }
}
pub fn month_name(lang: Lang, m: u32, _fallback: &'static str) -> &'static str {
    const VI_MONTHS: [&str; 12] = [
        "Tháng 1",
        "Tháng 2",
        "Tháng 3",
        "Tháng 4",
        "Tháng 5",
        "Tháng 6",
        "Tháng 7",
        "Tháng 8",
        "Tháng 9",
        "Tháng 10",
        "Tháng 11",
        "Tháng 12",
    ];
    const EN_MONTHS: [&str; 12] = [
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    ];
    let i = (m.max(1) - 1) as usize % 12;
    match lang {
        Lang::Vi => VI_MONTHS[i],
        Lang::En => EN_MONTHS[i],
    }
}
pub fn weekday_labels(
    lang: Lang,
    monday_first: bool,
    _fallback: [&'static str; 7],
) -> [&'static str; 7] {
    match (lang, monday_first) {
        (Lang::Vi, true) => ["T2", "T3", "T4", "T5", "T6", "T7", "CN"],
        (Lang::Vi, false) => ["CN", "T2", "T3", "T4", "T5", "T6", "T7"],
        (Lang::En, true) => ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"],
        (Lang::En, false) => ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    }
}
